import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Customer, PickedAllocation, Product } from '../types';
import { formatDate, formatPKR } from '../rules/rulesEngine';

export interface PickListPdfData {
  orderNo: string;
  todayDate: string;
  customer: Customer;
  role: string;
  lines: {
    lineId: string;
    sku: string;
    productName: string;
    category: string;
    unit: string;
    requestedQty: number;
    allocatedBatches: PickedAllocation[];
    shortfall: number;
    shortfallReason?: string;
  }[];
  totalQty: number;
  totalValue: number;
}

export function generatePickListPdf(data: PickListPdfData, action: 'download' | 'print' = 'download'): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Primary palette: Deep Forest Green (#14532D)
  const primaryGreen = [20, 83, 45] as const;
  const darkNeutral = [38, 38, 38] as const;
  const mutedText = [115, 115, 115] as const;
  const lightBg = [250, 247, 242] as const;

  // Header Background Bar
  doc.setFillColor(primaryGreen[0], primaryGreen[1], primaryGreen[2]);
  doc.rect(0, 0, pageWidth, 24, 'F');

  // Company and Title in Header
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('ShelfSense · Demo Foods Pvt Ltd', 14, 11);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text('Multan Plant · Food & Agro Division · Industrial Estate Phase II', 14, 17);

  // Document Title Badge on Right
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('DISPATCH PICK LIST', pageWidth - 14, 11, { align: 'right' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text('FEFO Verified & Enforced', pageWidth - 14, 17, { align: 'right' });

  // Academic notice banner under header
  doc.setFillColor(245, 245, 244);
  doc.rect(0, 24, pageWidth, 7, 'F');
  doc.setTextColor(120, 53, 15); // amber-900
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'bold');
  doc.text('ACADEMIC PROTOTYPE – SYNTHETIC DATA – ALL QUANTITIES VERIFIED FOR DEMONSTRATION', 14, 28.5);

  // Metadata Grid: Order & Customer Information
  let currentY = 37;

  // Left column: Order Info
  doc.setTextColor(darkNeutral[0], darkNeutral[1], darkNeutral[2]);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('Pick Slip / Order Details:', 14, currentY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  currentY += 4.5;
  doc.text(`Order Number: ${data.orderNo}`, 14, currentY);
  currentY += 4;
  doc.text(`Issue Date: ${formatDate(data.todayDate)}`, 14, currentY);
  currentY += 4;
  doc.text(`Generated By: ${data.role} Operator`, 14, currentY);
  currentY += 4;
  doc.text(`Warehouse Zone: South Punjab Hub (WH-1 & WH-2)`, 14, currentY);

  // Right column: Customer & Shelf-Life Profile
  let rightY = 37;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('Customer & Channel Requirements:', pageWidth / 2 + 5, rightY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  rightY += 4.5;
  doc.text(`Customer Name: ${data.customer.name}`, pageWidth / 2 + 5, rightY);
  rightY += 4;
  doc.text(`Channel Type: ${data.customer.type} (${data.customer.city})`, pageWidth / 2 + 5, rightY);
  rightY += 4;
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(primaryGreen[0], primaryGreen[1], primaryGreen[2]);
  doc.text(`Enforced Min Shelf-Life: ${data.customer.minRemainingShelfLifeDays} Days Left`, pageWidth / 2 + 5, rightY);
  doc.setTextColor(darkNeutral[0], darkNeutral[1], darkNeutral[2]);
  doc.setFont('helvetica', 'normal');
  rightY += 4;
  doc.text(`Contact: ${data.customer.contactPerson}`, pageWidth / 2 + 5, rightY);

  currentY = Math.max(currentY, rightY) + 7;

  // Table Data Preparation
  const tableRows: any[] = [];
  let lineCounter = 1;

  for (const line of data.lines) {
    if (line.allocatedBatches.length > 0) {
      for (const alloc of line.allocatedBatches) {
        tableRows.push([
          String(lineCounter++),
          line.sku,
          line.productName,
          alloc.batchNo,
          alloc.location,
          formatDate(alloc.expiryDate),
          `${alloc.daysLeft}d left`,
          `${alloc.qty} ${line.unit}`,
          '[   ]', // physical checkbox for warehouse picker clipboard
          alloc.isOverride ? `OVERRIDE: ${alloc.overrideReason || 'Manual'}` : alloc.reason,
        ]);
      }
    } else {
      // Shortfall / Unfulfilled line
      tableRows.push([
        String(lineCounter++),
        line.sku,
        line.productName,
        'NONE',
        '-',
        '-',
        '-',
        `0 / ${line.requestedQty} ${line.unit}`,
        '[   ]',
        line.shortfallReason || 'No eligible batches meeting customer shelf-life limits',
      ]);
    }
  }

  // Draw Pick Items Table with autoTable
  autoTable(doc, {
    startY: currentY,
    head: [
      [
        '#',
        'SKU',
        'Product Description',
        'Batch No',
        'Location',
        'Expiry Date',
        'Days Left',
        'Pick Qty',
        'Picked',
        'FEFO Selection Reason & Notes',
      ],
    ],
    body: tableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [20, 83, 45],
      textColor: [255, 255, 255],
      fontSize: 7.5,
      fontStyle: 'bold',
      halign: 'left',
    },
    bodyStyles: {
      fontSize: 7,
      textColor: [38, 38, 38],
      cellPadding: 2,
    },
    columnStyles: {
      0: { cellWidth: 7, halign: 'center' },
      1: { cellWidth: 18, fontStyle: 'bold' },
      2: { cellWidth: 32 },
      3: { cellWidth: 20, fontStyle: 'bold' },
      4: { cellWidth: 16 },
      5: { cellWidth: 18 },
      6: { cellWidth: 14, halign: 'center' },
      7: { cellWidth: 15, halign: 'right', fontStyle: 'bold' },
      8: { cellWidth: 12, halign: 'center' },
      9: { cellWidth: 'auto' },
    },
    alternateRowStyles: {
      fillColor: [250, 250, 249],
    },
    margin: { left: 14, right: 14 },
    didDrawPage: (hookData) => {
      // Footer on every page
      doc.setFontSize(7);
      doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
      doc.text(
        'Academic prototype – synthetic data – decisions require human approval.',
        14,
        pageHeight - 8
      );
      doc.text(
        `Page ${hookData.pageNumber} of ${doc.getNumberOfPages()}`,
        pageWidth - 14,
        pageHeight - 8,
        { align: 'right' }
      );
    },
  });

  // Calculate final Y position after table
  const finalY = (doc as any).lastAutoTable ? (doc as any).lastAutoTable.finalY + 8 : currentY + 40;

  // Check if we need to add a page for summary and signatures
  let summaryY = finalY;
  if (summaryY > pageHeight - 55) {
    doc.addPage();
    summaryY = 20;
  }

  // Summary Box
  doc.setFillColor(245, 245, 244);
  doc.roundedRect(14, summaryY, pageWidth - 28, 16, 2, 2, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(darkNeutral[0], darkNeutral[1], darkNeutral[2]);
  doc.text(`Total Items Picked: ${data.totalQty} Units`, 18, summaryY + 6);
  doc.text(`Estimated Order Value: ${formatPKR(data.totalValue)}`, 18, summaryY + 11.5);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
  doc.text(
    `Pick Verification: Warehouse floor staff must sign below and check each bin pallet before releasing to carrier.`,
    pageWidth / 2 - 10,
    summaryY + 8.5
  );

  // Signatures Section
  const signY = summaryY + 24;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(darkNeutral[0], darkNeutral[1], darkNeutral[2]);

  const colWidth = (pageWidth - 28) / 4;

  // Sig 1
  doc.line(14, signY + 6, 14 + colWidth - 5, signY + 6);
  doc.text('Picked By (Warehouse)', 14, signY + 10);
  doc.text('Date: ________________', 14, signY + 14);

  // Sig 2
  doc.line(14 + colWidth, signY + 6, 14 + colWidth * 2 - 5, signY + 6);
  doc.text('Verified By (QA Officer)', 14 + colWidth, signY + 10);
  doc.text('Date: ________________', 14 + colWidth, signY + 14);

  // Sig 3
  doc.line(14 + colWidth * 2, signY + 6, 14 + colWidth * 3 - 5, signY + 6);
  doc.text('Approved By (Supervisor)', 14 + colWidth * 2, signY + 10);
  doc.text('Date: ________________', 14 + colWidth * 2, signY + 14);

  // Sig 4
  doc.line(14 + colWidth * 3, signY + 6, pageWidth - 14, signY + 6);
  doc.text('Driver / Carrier Acknowledgement', 14 + colWidth * 3, signY + 10);
  doc.text('Vehicle #: ____________', 14 + colWidth * 3, signY + 14);

  // Output action: Download or Print
  const fileName = `ShelfSense_PickList_${data.orderNo}_${data.todayDate}.pdf`;

  if (action === 'print') {
    // Open PDF in a new window and trigger print dialog
    const pdfBlob = doc.output('blob');
    const blobUrl = URL.createObjectURL(pdfBlob);
    const printWindow = window.open(blobUrl, '_blank');
    if (printWindow) {
      printWindow.focus();
    }
  } else {
    // Direct file download
    doc.save(fileName);
  }
}
